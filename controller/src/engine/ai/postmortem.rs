//! Postmortem Writer: turns an incident room plus the actions taken during it into a Markdown
//! postmortem (summary, impact, timeline, root cause, actions, follow-ups).
//!
//! The text is built from recorded data only. Where the data does not say something (no root cause,
//! no actions) the document says so instead of inventing it, so a draft is safe to hand to a person
//! to finish. Read-only.

use chrono::{DateTime, Utc};
use serde::Serialize;
use uuid::Uuid;

use super::incident_commander::{open_room, IncidentRoom};
use crate::db::DbPool;

#[derive(Debug, Clone, Serialize, PartialEq)]
pub struct ActionTaken {
    pub label: String,
    pub action_type: String,
    pub status: String,
    pub requested_by: String,
    pub at: String,
}

#[derive(Debug, Serialize)]
pub struct Postmortem {
    pub incident_id: Uuid,
    pub title: String,
    pub markdown: String,
}

fn fmt(t: DateTime<Utc>) -> String {
    t.format("%Y-%m-%d %H:%M UTC").to_string()
}

/// Escape characters that would break a Markdown table cell or start a heading.
fn cell(s: &str) -> String {
    s.replace('|', "\\|").replace(['\n', '\r'], " ")
}

pub fn render(room: &IncidentRoom, actions: &[ActionTaken]) -> String {
    let i = &room.incident;
    let mut md = String::new();
    md.push_str(&format!("# Postmortem: {}\n\n", i.title.replace('\n', " ")));
    md.push_str(&format!(
        "- **Severity:** {}\n- **Status:** {}\n- **Opened:** {}\n",
        i.severity,
        i.status,
        fmt(i.created_at)
    ));
    if let (Some(a), Some(b)) = (i.window_start, i.window_end) {
        let mins = (b - a).num_minutes().max(0);
        md.push_str(&format!(
            "- **Detection window:** {} to {} ({} min)\n",
            fmt(a),
            fmt(b),
            mins
        ));
    }
    md.push_str("\n## Summary\n\n");
    if i.summary.trim().is_empty() {
        md.push_str("_No summary was recorded._\n");
    } else {
        md.push_str(i.summary.trim());
        md.push('\n');
    }

    md.push_str("\n## Impact\n\n");
    if i.affected_resources.is_empty() {
        md.push_str("_No affected resources were recorded._\n");
    } else {
        for r in &i.affected_resources {
            md.push_str(&format!("- {}\n", r.replace('\n', " ")));
        }
    }

    md.push_str("\n## Root cause\n\n");
    match i
        .root_cause
        .as_deref()
        .map(str::trim)
        .filter(|s| !s.is_empty())
    {
        Some(rc) => {
            md.push_str(rc);
            md.push('\n');
        }
        None => md.push_str(
            "_Not determined. This needs a person to confirm before the postmortem is final._\n",
        ),
    }

    md.push_str("\n## Timeline\n\n");
    if room.timeline.is_empty() {
        md.push_str("_No events were correlated for this window._\n");
    } else {
        md.push_str("| Time | Source | Severity | Event |\n|---|---|---|---|\n");
        for e in &room.timeline {
            md.push_str(&format!(
                "| {} | {} | {} | {} |\n",
                fmt(e.at),
                cell(&e.source),
                cell(&e.severity),
                cell(&e.message)
            ));
        }
    }

    md.push_str("\n## Actions taken\n\n");
    if actions.is_empty() {
        md.push_str("_No Zyra actions were proposed during this window._\n");
    } else {
        md.push_str("| Time | Action | Status | Requested by |\n|---|---|---|---|\n");
        for a in actions {
            md.push_str(&format!(
                "| {} | {} (`{}`) | {} | {} |\n",
                cell(&a.at),
                cell(&a.label),
                cell(&a.action_type),
                cell(&a.status),
                cell(&a.requested_by)
            ));
        }
    }

    md.push_str("\n## Follow-ups\n\n");
    let mut n = 0;
    for step in &room.runbook_steps {
        md.push_str(&format!("- [ ] {}\n", step.replace('\n', " ")));
        n += 1;
    }
    if i.root_cause.is_none() {
        md.push_str("- [ ] Confirm the root cause\n");
        n += 1;
    }
    if room.pending_approvals > 0 {
        md.push_str(&format!(
            "- [ ] Decide on {} pending approval(s) in the queue\n",
            room.pending_approvals
        ));
        n += 1;
    }
    if n == 0 {
        md.push_str("_None suggested._\n");
    }
    md.push_str("\n---\n_Draft generated by Zyra from recorded data. Review before sharing._\n");
    md
}

pub async fn generate(pool: &DbPool, incident_id: Uuid) -> anyhow::Result<Postmortem> {
    let room = open_room(pool, incident_id).await?;
    let from = room
        .incident
        .window_start
        .unwrap_or(room.incident.created_at);
    let to = room.incident.window_end.unwrap_or_else(Utc::now);
    let rows: Vec<(String, String, String, String, String)> = crate::db::query_as(
        "SELECT label, action_type, status, requested_by,
                strftime('%Y-%m-%d %H:%M UTC', created_at) AS at
         FROM ai_actions
         WHERE strftime('%Y-%m-%dT%H:%M:%SZ', created_at) >= ?
           AND strftime('%Y-%m-%dT%H:%M:%SZ', created_at) <= ?
         ORDER BY created_at ASC LIMIT 50",
    )
    .bind(from.format("%Y-%m-%dT%H:%M:%SZ").to_string())
    .bind(to.format("%Y-%m-%dT%H:%M:%SZ").to_string())
    .fetch_all(pool)
    .await?;
    let actions: Vec<ActionTaken> = rows
        .into_iter()
        .map(
            |(label, action_type, status, requested_by, at)| ActionTaken {
                label,
                action_type,
                status,
                requested_by,
                at,
            },
        )
        .collect();
    Ok(Postmortem {
        incident_id,
        title: room.incident.title.clone(),
        markdown: render(&room, &actions),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::engine::ai::incident_commander::ActiveIncident;
    use crate::engine::ai::root_cause::TimelineEntry;
    use chrono::TimeZone;

    fn room(root_cause: Option<&str>, timeline: Vec<TimelineEntry>) -> IncidentRoom {
        let t = Utc.with_ymd_and_hms(2026, 11, 3, 10, 0, 0).unwrap();
        IncidentRoom {
            incident: ActiveIncident {
                id: Uuid::nil(),
                title: "Storage stall".into(),
                summary: "".into(),
                severity: "high".into(),
                status: "investigating".into(),
                affected_resources: vec!["web-1".into()],
                root_cause: root_cause.map(String::from),
                created_at: t,
                window_start: Some(t),
                window_end: Some(t + chrono::Duration::minutes(45)),
            },
            timeline,
            runbook_steps: vec!["Check the pool".into()],
            pending_approvals: 2,
            correlated_count: 1,
        }
    }

    #[test]
    fn missing_data_is_stated_not_invented() {
        let md = render(&room(None, vec![]), &[]);
        assert!(md.contains("_No summary was recorded._"));
        assert!(md.contains("_Not determined."));
        assert!(md.contains("_No events were correlated"));
        assert!(md.contains("_No Zyra actions were proposed"));
        assert!(md.contains("- [ ] Confirm the root cause"));
        assert!(md.contains("Decide on 2 pending approval(s)"));
        assert!(md.contains("(45 min)"));
    }

    #[test]
    fn table_cells_cannot_break_the_table() {
        let t = Utc.with_ymd_and_hms(2026, 11, 3, 10, 5, 0).unwrap();
        let tl = vec![TimelineEntry {
            at: t,
            source: "agent".into(),
            kind: "event".into(),
            message: "a | b\nc".into(),
            severity: "high".into(),
        }];
        let md = render(&room(Some("Disk full"), tl), &[]);
        assert!(md.contains("a \\| b c"));
        assert!(md.contains("Disk full"));
        assert!(!md.contains("_Not determined."));
    }

    #[test]
    fn actions_are_listed_with_their_status() {
        let a = ActionTaken {
            label: "Start web-1".into(),
            action_type: "start_vm".into(),
            status: "executed".into(),
            requested_by: "zyra".into(),
            at: "2026-11-03 10:10 UTC".into(),
        };
        let md = render(&room(Some("x"), vec![]), &[a]);
        assert!(md.contains("| Start web-1 (`start_vm`) | executed | zyra |"));
    }

    #[tokio::test]
    async fn an_unknown_incident_is_an_error() {
        let pool = crate::db::testing::pool().await;
        assert!(generate(&pool, Uuid::new_v4()).await.is_err());
    }

    #[tokio::test]
    async fn a_stored_incident_produces_a_draft_with_the_actions_query_prepared() {
        let pool = crate::db::testing::pool().await;
        let id = Uuid::new_v4();
        crate::db::query(
            "INSERT INTO ai_incidents (id, title, summary, severity, status, affected_resources, root_cause)
             VALUES (?, 'Disk stall', 'Slow disk', 'high', 'open', '[\"web-1\"]', 'Pool full')",
        )
        .bind(id)
        .execute(&pool)
        .await
        .unwrap();
        let pm = generate(&pool, id).await.unwrap();
        assert!(pm.markdown.contains("# Postmortem: Disk stall"));
        assert!(pm.markdown.contains("Pool full"));
    }
}
