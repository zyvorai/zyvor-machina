//! Network boot for bare metal: the dnsmasq configuration a site's boot host runs
//! (proxyDHCP + TFTP, so it coexists with the site DHCP server), the iPXE script that
//! boots the commissioning image, and the script that image runs.
//!
//! Everything here renders text. Running dnsmasq and shipping the kernel, initrd and
//! rootfs is the operator's boot host (see docs/baremetal-provisioning.md).

use uuid::Uuid;

/// `aa:bb:cc:dd:ee:ff` in lower case, or `None` if `s` is not a MAC address.
pub fn normalize_mac(s: &str) -> Option<String> {
    let t: String = s
        .trim()
        .chars()
        .filter(|c| !matches!(c, ':' | '-' | '.'))
        .collect::<String>()
        .to_ascii_lowercase();
    if t.len() != 12 || !t.chars().all(|c| c.is_ascii_hexdigit()) {
        return None;
    }
    let pairs: Vec<&str> = (0..6).map(|i| &t[i * 2..i * 2 + 2]).collect();
    Some(pairs.join(":"))
}

pub struct BootConfig<'a> {
    /// Network the boot host serves, e.g. `10.20.0.0` (proxyDHCP answers machines on it).
    pub subnet: &'a str,
    /// Directory holding the iPXE binaries (`undionly.kpxe`, `ipxe.efi`).
    pub tftp_root: &'a str,
    /// Controller base URL the iPXE script is fetched from.
    pub controller_url: &'a str,
    /// Interface to bind; empty for all.
    pub interface: &'a str,
}

fn safe_token(s: &str) -> bool {
    !s.is_empty()
        && s.chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '/' | ':' | '_' | '-'))
}

/// dnsmasq in proxyDHCP mode: it never hands out addresses, it only tells PXE clients
/// what to boot. A client that is already running iPXE is sent to the controller's script.
pub fn dnsmasq_conf(c: &BootConfig<'_>) -> anyhow::Result<String> {
    for (name, v) in [
        ("subnet", c.subnet),
        ("tftp_root", c.tftp_root),
        ("controller_url", c.controller_url),
    ] {
        if !safe_token(v) {
            anyhow::bail!("{name} contains characters that cannot go in a dnsmasq config");
        }
    }
    if !c.interface.is_empty() && !safe_token(c.interface) {
        anyhow::bail!("interface contains characters that cannot go in a dnsmasq config");
    }
    let mut s =
        String::from("# Generated by Machina. proxyDHCP + TFTP for bare-metal commissioning.\n");
    s += "port=0\nlog-dhcp\nenable-tftp\n";
    s += &format!("tftp-root={}\n", c.tftp_root);
    if !c.interface.is_empty() {
        s += &format!("interface={}\nbind-interfaces\n", c.interface);
    }
    s += &format!("dhcp-range={},proxy\n", c.subnet);
    s += "dhcp-match=set:ipxe,175\n";
    s += "pxe-service=tag:!ipxe,x86PC,\"iPXE (BIOS)\",undionly.kpxe\n";
    s += "pxe-service=tag:!ipxe,BC_EFI,\"iPXE (UEFI)\",ipxe.efi\n";
    s += "pxe-service=tag:!ipxe,X86-64_EFI,\"iPXE (UEFI x64)\",ipxe.efi\n";
    s += "pxe-service=tag:!ipxe,ARM64_EFI,\"iPXE (UEFI arm64)\",ipxe-arm64.efi\n";
    s += &format!(
        "dhcp-boot=tag:ipxe,{}/api/v1/baremetal/boot/ipxe\n",
        c.controller_url.trim_end_matches('/')
    );
    Ok(s)
}

/// The iPXE script for a machine that is being commissioned.
pub fn ipxe_commission_script(
    controller_url: &str,
    server_id: Uuid,
    token: &str,
    assets_base: &str,
) -> String {
    let c = controller_url.trim_end_matches('/');
    let a = assets_base.trim_end_matches('/');
    format!(
        "#!ipxe\n\
         kernel {a}/metal-vmlinuz initrd=metal-initrd ip=dhcp boot=live fetch={a}/metal-rootfs.squashfs \
         machina.report={c}/api/v1/baremetal/commissioning/{server_id}/report machina.token={token} \
         machina.script={c}/api/v1/baremetal/boot/commission.sh\n\
         initrd --name metal-initrd {a}/metal-initrd\n\
         boot\n"
    )
}

/// iPXE script for a machine the controller does not want to boot: fall through to disk.
pub fn ipxe_exit_script() -> &'static str {
    "#!ipxe\nexit\n"
}

/// What the commissioning image runs. It reads `machina.report`, `machina.token` from
/// the kernel command line, collects hardware facts and posts one JSON document. With
/// `--print` it only prints the document (for testing on any Linux box).
pub const COMMISSION_SCRIPT: &str = r#"#!/bin/sh
# Machina bare-metal commissioning. Reads /proc/cmdline for machina.report and
# machina.token, gathers hardware facts, runs short tests, posts the result.
set -u
PRINT=0; [ "${1:-}" = "--print" ] && PRINT=1
exec python3 - "$PRINT" <<'PY'
import json, os, re, subprocess, sys, urllib.request

def run(*a):
    try:
        return subprocess.run(a, capture_output=True, text=True, timeout=60).stdout
    except Exception:
        return ""

def cmdline(key):
    for part in open("/proc/cmdline").read().split():
        if part.startswith(key + "="):
            return part.split("=", 1)[1]
    return ""

meminfo = open("/proc/meminfo").read()
mem_kb = int(re.search(r"MemTotal:\s+(\d+)", meminfo).group(1))
cpus = sum(1 for l in open("/proc/cpuinfo") if l.startswith("processor"))

disks = []
try:
    for d in json.loads(run("lsblk", "-J", "-b", "-d", "-o", "NAME,SIZE,ROTA,TYPE,MODEL,SERIAL")).get("blockdevices", []):
        if d.get("type") == "disk":
            disks.append({"name": d["name"], "size_bytes": int(d.get("size") or 0),
                          "rotational": str(d.get("rota")) in ("1", "True", "true"),
                          "model": (d.get("model") or "").strip(), "serial": (d.get("serial") or "").strip()})
except Exception:
    pass

nics = []
base = "/sys/class/net"
for n in sorted(os.listdir(base)):
    if n == "lo" or not os.path.exists(f"{base}/{n}/address"):
        continue
    if os.path.exists(f"{base}/{n}/device") is False:
        continue
    def rd(p):
        try:
            return open(f"{base}/{n}/{p}").read().strip()
        except Exception:
            return ""
    speed = rd("speed")
    nics.append({"name": n, "mac": rd("address"), "link": rd("operstate"),
                 "speed_mbps": int(speed) if speed.lstrip("-").isdigit() and int(speed) > 0 else 0})

def dmi(k):
    try:
        return open(f"/sys/class/dmi/id/{k}").read().strip()
    except Exception:
        return ""

tests = [{"name": "cpu", "passed": cpus > 0, "detail": f"{cpus} logical CPUs"},
         {"name": "memory", "passed": mem_kb > 0, "detail": f"{mem_kb // 1024} MiB"},
         {"name": "disks", "passed": len(disks) > 0, "detail": f"{len(disks)} disks"},
         {"name": "network", "passed": any(n["link"] == "up" for n in nics), "detail": f"{len(nics)} NICs"}]

report = {"cpu_cores": cpus, "memory_mib": mem_kb // 1024, "disks": disks, "nics": nics,
          "dmi": {"vendor": dmi("sys_vendor"), "product": dmi("product_name"),
                  "serial": dmi("product_serial"), "bios": dmi("bios_version")},
          "tests": tests}

if sys.argv[1] == "1":
    print(json.dumps(report, indent=2))
    sys.exit(0)

url, token = cmdline("machina.report"), cmdline("machina.token")
req = urllib.request.Request(url, data=json.dumps(report).encode(), method="POST",
                             headers={"Authorization": "Bearer " + token, "Content-Type": "application/json"})
urllib.request.urlopen(req, timeout=60).read()
PY
"#;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mac_addresses_normalise() {
        assert_eq!(
            normalize_mac("AA-BB-CC-DD-EE-FF").as_deref(),
            Some("aa:bb:cc:dd:ee:ff")
        );
        assert_eq!(
            normalize_mac("aabb.ccdd.eeff").as_deref(),
            Some("aa:bb:cc:dd:ee:ff")
        );
        assert_eq!(normalize_mac("aa:bb:cc"), None);
        assert_eq!(normalize_mac("zz:bb:cc:dd:ee:ff"), None);
    }

    #[test]
    fn dnsmasq_is_proxy_only_and_chains_ipxe() {
        let c = dnsmasq_conf(&BootConfig {
            subnet: "10.20.0.0",
            tftp_root: "/srv/tftp",
            controller_url: "https://ctl.example:5093/",
            interface: "eth1",
        })
        .unwrap();
        assert!(c.contains("port=0"));
        assert!(c.contains("dhcp-range=10.20.0.0,proxy"));
        assert!(c.contains("tftp-root=/srv/tftp"));
        assert!(c.contains("interface=eth1"));
        assert!(
            c.contains("dhcp-boot=tag:ipxe,https://ctl.example:5093/api/v1/baremetal/boot/ipxe")
        );
        assert!(c.contains("ipxe.efi") && c.contains("undionly.kpxe"));
    }

    #[test]
    fn dnsmasq_refuses_values_that_could_inject_config() {
        let bad = BootConfig {
            subnet: "10.0.0.0\ndhcp-script=/tmp/x",
            tftp_root: "/srv/tftp",
            controller_url: "https://c",
            interface: "",
        };
        assert!(dnsmasq_conf(&bad).is_err());
    }

    #[test]
    fn ipxe_script_carries_report_url_and_token() {
        let id = Uuid::from_u128(7);
        let s = ipxe_commission_script("https://c:5093/", id, "tok123", "https://c:5093/dist/");
        assert!(s.starts_with("#!ipxe\n"));
        assert!(s.contains(&format!(
            "machina.report=https://c:5093/api/v1/baremetal/commissioning/{id}/report"
        )));
        assert!(s.contains("machina.token=tok123"));
        assert!(s.contains("https://c:5093/dist/metal-vmlinuz"));
        assert!(s.trim_end().ends_with("boot"));
    }
}
