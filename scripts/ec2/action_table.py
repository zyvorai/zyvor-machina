def read(name):
    return (SRC / name).read_text()


def fn_body(text, signature):
    i = text.index(signature)
    j = text.index("\n}\n", i)
    return text[i:j]


ARM = re.compile(r'^\s*((?:"[A-Za-z0-9]+"\s*\|?\s*)+)(?:if [^\n]*?)?=>', re.M)


def arms(body):
    out = []
    for m in ARM.finditer(body):
        out += re.findall(r'"([A-Za-z0-9]+)"', m.group(1))
    return out


def actions():
    ec2 = sorted(set(arms(fn_body(read("mod.rs"), "async fn dispatch("))))
    mon = sorted(set(arms(fn_body(read("services.rs"), "async fn monitoring_dispatch("))))
    asg = sorted(set(arms(fn_body(read("autoscaling.rs"), "pub async fn dispatch("))))
    elb = sorted(set(arms(fn_body(read("elbv2.rs"), "pub async fn dispatch("))))
    return {"ec2": ec2, "monitoring": mon, "autoscaling": asg, "elasticloadbalancing": elb}


def filters():
    text = read("foundation.rs")
    block = text[text.index("pub const FILTER_SPECS"):text.index("fn spec_for")]
    rows = []
    for m in re.finditer(r'action:\s*"(\w+)",(.*?)(?=\n    FilterSpec|\n\];)', block, re.S):
        action, rest = m.group(1), m.group(2)
        names = re.findall(r'(?:native|field)\("([\w.\-]+)"', rest)
        tags = "native_tags: true" in rest
        rows.append((action, names))
    # one-line specs
    for m in re.finditer(r'FilterSpec \{ action: "(\w+)", native_tags: (\w+), filters: &\[(.*?)\] \}', block):
        names = re.findall(r'(?:native|field)\("([\w.\-]+)"', m.group(3))
        rows.append((m.group(1), names))
    seen = {}
    for a, n in rows:
        seen.setdefault(a, n)
    return sorted(seen.items())


def render():
    acts = actions()
    for (svc, name) in S:
        if name not in acts[svc]:
            sys.exit(f"STATUS has an entry for {svc} {name}, which is not in the action match: remove or fix it")
    lines = []
    lines.append(BEGIN)
    lines.append("")
    lines.append("Status of each action (judged by reading its handler; **none of this has been run with a real client**, see *What has been run*):")
    lines.append("")
    for k, v in LEGEND:
        lines.append(f"- `{k}`: {v}")
    lines.append("")
    lines.append("An action that is not in these tables answers `UnsupportedOperation` on `ec2` and `InvalidAction` on the other services.")
    titles = {
        "ec2": ("ec2", "scope `ec2`, `POST /ec2`"),
        "monitoring": ("monitoring", "scope `monitoring`, `POST /monitoring`"),
        "autoscaling": ("autoscaling", "scope `autoscaling`, `POST /autoscaling`"),
        "elasticloadbalancing": ("elasticloadbalancing (ELBv2)", "scope `elasticloadbalancing`, `POST /elbv2`"),
    }
    for svc in ["ec2", "autoscaling", "elasticloadbalancing", "monitoring"]:
        title, scope = titles[svc]
        names = acts[svc]
        counts = {}
        for n in names:
            st = S.get((svc, n), ("real", ""))[0]
            counts[st] = counts.get(st, 0) + 1
        summary = ", ".join(f"{v} {k}" for k, v in sorted(counts.items()))
        lines.append("")
        lines.append(f"### {title} actions ({len(names)}: {summary})")
        lines.append("")
        lines.append(f"Reached with {scope}.")
        lines.append("")
        if svc == "ec2":
            lines.append("`M` in the last column marks Machina's own actions (not AWS ones); a stock SDK has no call for them.")
            lines.append("")
            lines.append("| Action | Status | Note | |")
            lines.append("|---|---|---|---|")
        else:
            lines.append("| Action | Status | Note |")
            lines.append("|---|---|---|")
        for n in names:
            st, note = S.get((svc, n), ("real", ""))
            if svc == "ec2":
                lines.append(f"| `{n}` | {st} | {note} | {'M' if n in MACHINA else ''} |")
            else:
                lines.append(f"| `{n}` | {st} | {note} |")
    lines.append("")
    lines.append("### Filter names")
    lines.append("")
    lines.append("Only the `ec2` service validates filters. An `ec2` describe not listed here accepts the filters it implements and does not check names. Every listed describe also takes `tag:KEY`, `tag-key` and `tag-value`.")
    lines.append("")
    lines.append("| Describe | Filter names |")
    lines.append("|---|---|")
    for a, names in filters():
        lines.append(f"| `{a}` | {', '.join(f'`{n}`' for n in names) if names else '(none besides tag filters)'} |")
    lines.append("")
    lines.append(END)
    return "\n".join(lines)


def main():
    block = render()
    doc = DOC.read_text()
    if BEGIN not in doc or END not in doc:
        sys.exit(f"{DOC} has no generated block markers")
    new = doc[:doc.index(BEGIN)] + block + doc[doc.index(END) + len(END):]
    if "--check" in sys.argv:
        if new != doc:
            print("docs/cloud-ec2-api.md action tables are out of date: run scripts/ec2/action_table.py")
            sys.exit(1)
        print("action tables are up to date")
        return
    DOC.write_text(new)
    print("rewrote the generated block:", {k: len(v) for k, v in actions().items()})


if __name__ == "__main__":
    main()
